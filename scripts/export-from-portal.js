'use strict';
// Reads the live portal SQLite and writes:
//   js/fixture.js   — read-only preview data bundled with the app
//   data/export.json — the same data, used by scripts/migrate.js on deploy day
// Run: node scripts/export-from-portal.js   (uses the portal repo's better-sqlite3)
const fs = require('fs');
const path = require('path');

const PORTAL = '/Users/liamnorris/Claude/qis-production-portal';
const Database = require(path.join(PORTAL, 'node_modules', 'better-sqlite3'));
const db = new Database(path.join(PORTAL, 'data', 'portal.sqlite'), { readonly: true });

const entries = db.prepare(`SELECT id, entry_date, person, customer, order_ref, revenue_cents,
  gp_pct, lead_source, created_by FROM sales_entries WHERE deleted_at IS NULL ORDER BY entry_date, id`).all();
const targets = db.prepare('SELECT person, month, amount FROM targets ORDER BY person, month').all();
const holidays = db.prepare('SELECT date, name FROM holidays ORDER BY date').all();
const roster = db.prepare("SELECT person FROM roster WHERE active=1 AND person != 'Team Win' ORDER BY rowid").all()
  .map((r) => r.person);

const payload = { exportedAt: new Date().toISOString(), entries, targets, holidays, roster };

fs.mkdirSync(path.join(__dirname, '..', 'data'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'data', 'export.json'), JSON.stringify(payload, null, 1));
fs.writeFileSync(path.join(__dirname, '..', 'js', 'fixture.js'),
  `'use strict';\n// Read-only preview data (auto-generated by scripts/export-from-portal.js).\nwindow.QIS_FIXTURE = ${JSON.stringify(payload)};\n`);

const total = entries.reduce((s, e) => s + e.revenue_cents, 0) / 100;
console.log(`exported ${entries.length} entries ($${total.toFixed(2)}), ${targets.length} targets, ${holidays.length} holidays, roster: ${roster.join(', ')}`);
